# -*- coding: utf-8 -*-
"""v104.12: детект лимита запросов и расписание спящего режима.

Последний из четырёх гардрейлов: сайты бесплатных чатов ограничивают
частоту запросов (HTTP 429, баннеры «Высокая нагрузка», просьбы
подождать). Раньше агент либо висел до таймаута, либо принимал
мусорный ответ за настоящий. Теперь main._reply при признаках лимита
уходит в спящий режим с нарастающей паузой и повторяет ТОТ ЖЕ запрос;
если лимит не отпустил — честно останавливается с сообщением в панель.

ДВА ВИДА СБОЯ, ДВА РАСПИСАНИЯ. Изначально расписание было одно, потому что
режим был один — браузерный, где любой сбой означает «сайт держит лимит», и
ждать там надо минутами. По ключу API это стало неверно: 429 и обрыв связи —
принципиально разные события. Лимит отпускает через минуты, а перегрузка
шлюза (5xx) или разорванное соединение проходят за секунды, и полминуты
ожидания на ровном месте — это просто замерший редактор. Поэтому вид сбоя
теперь называется явно (KIND_LIMIT / KIND_OUTAGE) и выбирает своё расписание.

БРАУЗЕР СОЗНАТЕЛЬНО ОСТАВЛЕН НА СТАРОМ РАСПИСАНИИ. Сетевой монитор парсера
тоже репортит 5xx, но там за ними стоит не шлюз, а сам сайт бесплатного чата,
и частые повторы к нему — прямой путь к настоящей блокировке. Быстрое
расписание выбирает main._reply и только когда backend.kind == "api".
"""
import random

# Нарастающие паузы спящего режима, секунд. После исчерпания — остановка.
# Используются, когда провайдер НЕ сказал, сколько ждать (браузерные сайты не
# говорят никогда, часть API — тоже).
SLEEPS = [30, 60, 120, 300]

# Расписание для сбоя сервиса или связи (5xx, обрыв потока, тишина, DNS).
# Числа другого порядка, чем у SLEEPS, и это главное в них: перегрузка шлюза
# и разорванное соединение проходят за секунды. Сумма — около минуты, столько
# ожидания на неудачном запросе человек ещё готов терпеть, не нажимая «Стоп».
OUTAGE_SLEEPS = [2, 5, 12, 30]

# Разброс паузы сбоя, доля. Нужен не нам (в редакторе запрос ровно один), а
# сервису: когда шлюз падает, все установленные копии агента иначе приходят
# повторяться в одну и ту же секунду и добивают его уже сами.
OUTAGE_JITTER = 0.25

# Максимум, который мы согласны выждать по указанию провайдера. Заголовок
# Retry-After при СУТОЧНОМ лимите содержит часы, а держать редактор
# заблокированным на час нельзя: честнее сразу сказать пользователю, что
# лимит исчерпан, и дать ему выбрать другую модель или провайдера.
MAX_HONORED_RETRY_AFTER = 300

# Вид сбоя. Определяет и расписание пауз, и текст, который увидит пользователь,
# когда повторы кончатся: «сервис ограничивает запросы» и «не удалось
# дозвониться» — разные диагнозы и разные дальнейшие действия.
KIND_LIMIT = "limit"
KIND_OUTAGE = "outage"

# Метка сетевого сбоя на месте HTTP-статуса: обрыв потока, тишина в потоке,
# DNS, TLS, отказ прокси. Своё имя, а не выдуманный номер вроде 599 — потому
# что этот же статус попадает в текст для пользователя, и «HTTP 599» было бы
# ложью: никакого ответа от сервиса мы не получили вовсе.
TRANSPORT = "transport"

# Маркеры лимита в тексте ответа/баннера (нижний регистр).
MARKERS = [
    u"too many requests",
    u"rate limit",
    u"resource_exhausted",
    u"quota exceeded",
    u"высокая нагрузка",
    u"слишком много запросов",
    u"превышен лимит",
    u"попробуйте позже",
    u"try again later",
]

# Маркеры проверяются только на КОРОТКИХ ответах без действия: настоящий
# ответ модели может легитимно содержать слова «rate limit» (например, при
# работе над кодом самого агента), а баннеры лимита — это ~10 слов.
# v104.13: 400 -> 160 симв. (~15 слов): короткий НАСТОЯЩИЙ ответ вроде
# «Готово. Если снова упрётся в лимит — попробуйте позже» мог ложно
# считаться баннером лимита и усыплять агента на ровном месте.
MAX_TEXT_LEN_FOR_MARKERS = 160


def reason_from_text(text, action=None):
    """Причина лимита по тексту ответа или None."""
    if action:
        return None
    low = (text or u"").strip().lower()
    if not low or len(low) > MAX_TEXT_LEN_FOR_MARKERS:
        return None
    for m in MARKERS:
        if m in low:
            return u"маркер «%s» в ответе" % m
    return None


def reason_from_status(status):
    """Причина повтора по HTTP-статусу чат-эндпоинта (или метке TRANSPORT).
    None — повторять нечего."""
    if not status:
        return None
    if status == TRANSPORT:
        # Проверяется ДО int(): метка — строка, и int() на ней упал бы в
        # except, тихо отключив повтор сетевых сбоев.
        return u"обрыв связи с провайдером"
    try:
        status = int(status)
    except (TypeError, ValueError):
        return None
    if status == 429:
        return u"HTTP 429 (too many requests)"
    if status >= 500:
        return u"HTTP %d (сервис перегружен)" % status
    return None


def kind_from_status(status):
    """Вид сбоя: KIND_LIMIT, KIND_OUTAGE или None (повторять нечего).

    Разделение нужно ровно для двух решений: какое взять расписание пауз и что
    сказать пользователю, когда повторы кончились. 429 — это «сервис работает,
    но не для тебя сейчас»; 5xx и обрыв связи — «сервис не работает», и лечится
    это не ожиданием квоты, а повтором через пару секунд.
    """
    if not status:
        return None
    if status == TRANSPORT:
        return KIND_OUTAGE
    try:
        status = int(status)
    except (TypeError, ValueError):
        return None
    if status == 429:
        return KIND_LIMIT
    if status >= 500:
        return KIND_OUTAGE
    return None


def schedule_for(kind):
    """Расписание пауз для вида сбоя."""
    return OUTAGE_SLEEPS if kind == KIND_OUTAGE else SLEEPS


def sleep_seconds(attempt, retry_after=None, kind=KIND_LIMIT):
    """Пауза для попытки attempt (с нуля) или None, когда пора остановиться.

    retry_after — значение заголовка Retry-After от провайдера, в секундах.
    Если он назван, ждём ровно столько: провайдер знает про свои лимиты
    лучше любого нашего расписания, а угадывание приводит либо к лишнему
    простою, либо к повтору раньше срока и ещё одному 429. Разброс к такому
    значению НЕ добавляется: названный срок — это факт, а не наша догадка.

    kind выбирает расписание (см. KIND_LIMIT / KIND_OUTAGE). Значение по
    умолчанию — прежнее поведение: браузерный режим и всё, что не уточнило вид
    сбоя, продолжают работать по SLEEPS ровно как до появления работы по ключу.

    Число попыток ограничено длиной расписания даже с Retry-After: иначе
    провайдер, упорно отвечающий «подожди 5 секунд», держал бы агента в цикле
    бесконечно.
    """
    sleeps = schedule_for(kind)
    if attempt < 0 or attempt >= len(sleeps):
        return None
    if retry_after is not None:
        try:
            ra = int(float(retry_after))
        except (TypeError, ValueError):
            ra = None
        if ra is not None and ra >= 0:
            if ra > MAX_HONORED_RETRY_AFTER:
                return None
            return max(1, ra)
    base = sleeps[attempt]
    if kind == KIND_OUTAGE and OUTAGE_JITTER > 0:
        base = base * (1.0 + random.uniform(-OUTAGE_JITTER, OUTAGE_JITTER))
    return max(1, int(round(base)))
